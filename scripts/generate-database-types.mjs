import { spawnSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { format, resolveConfig } from 'prettier';

const root = fileURLToPath(new URL('../', import.meta.url));
const cli = fileURLToPath(new URL('../node_modules/supabase/dist/supabase.js', import.meta.url));
const destination = new URL('../src/types/database.ts', import.meta.url);
// No remote options or caller-provided flags: type generation is always local.
const result = spawnSync(
  process.execPath,
  [cli, 'gen', 'types', '--local', '--lang', 'typescript', '--schema', 'public,private'],
  {
    cwd: root,
    encoding: 'utf8',
    maxBuffer: 16 * 1024 * 1024,
    windowsHide: true,
  },
);
if (result.status !== 0) {
  console.error('Local Supabase type generation failed. Start the local stack first.');
  process.exit(1);
}
const start = result.stdout.indexOf('export type Json');
if (start < 0) throw new Error('Supabase did not return TypeScript types.');
const generated = await format(
  '// Generated by npm run db:types from local PostgreSQL. Do not edit.\n' +
    result.stdout.slice(start),
  { ...(await resolveConfig(fileURLToPath(destination))), parser: 'typescript' },
);
if (process.argv.includes('--check')) {
  if (readFileSync(destination, 'utf8').replaceAll('\r\n', '\n') !== generated) {
    console.error('Database type drift detected. Run npm run db:types.');
    process.exit(1);
  }
  console.log('Generated database types match local PostgreSQL.');
} else {
  writeFileSync(destination, generated, 'utf8');
  console.log('Generated src/types/database.ts from local PostgreSQL.');
}
